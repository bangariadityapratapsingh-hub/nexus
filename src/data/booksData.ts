// Helper to look up a subject by ID
export function getSubjectBooks(subjectId: string): SubjectBooksGroup | undefined {
  return BOOKS_DIRECTORY_DATA.find((s) => s.subjectId.toLowerCase() === subjectId.toLowerCase());
}

// Helper to filter books by Medium and Semester
export function filterBooks(
  books: BookItem[],
  mediumFilter: 'all' | 'hi' | 'en',
  semesterFilter: 'all' | number
): BookItem[] {
  return books.filter((b) => {
    const matchMedium =
      mediumFilter === 'all' || b.medium === 'both' || b.medium === mediumFilter;
    const matchSemester =
      semesterFilter === 'all' || b.semesters.includes(Number(semesterFilter));
    return matchMedium && matchSemester;
  });
}
