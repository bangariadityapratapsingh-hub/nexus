// Helper to look up an explorer subject with robust discipline keyword matching
export function getExplorerSubject(subjectIdOrCode?: string): ExplorerSubject {
  if (!subjectIdOrCode) return EXPLORER_SUBJECTS[0];
  const query = subjectIdOrCode.toLowerCase().trim();

  // 1. Direct equality on id or code
  const exact = EXPLORER_SUBJECTS.find(
    (s) => s.id.toLowerCase() === query || s.code.toLowerCase() === query
  );
  if (exact) return exact;

  // 2. Substring matching
  const substr = EXPLORER_SUBJECTS.find(
    (s) =>
      s.code.toLowerCase().includes(query) ||
      query.includes(s.id.toLowerCase())
  );
  if (substr) return substr;

  // 3. Discipline-specific keyword matching (prevents any non-geography subject falling back to Geography)
  if (query.includes('hin') || query.includes('हिंदी') || query.includes('हिन्दी')) {
    const s = EXPLORER_SUBJECTS.find((sub) => sub.id === 'hindi');
    if (s) return s;
  }
  if (query.includes('pol') || query.includes('राजनीति')) {
    const s = EXPLORER_SUBJECTS.find((sub) => sub.id === 'political-science');
    if (s) return s;
  }
  if (query.includes('his') || query.includes('इतिहास')) {
    const s = EXPLORER_SUBJECTS.find((sub) => sub.id === 'history');
    if (s) return s;
  }
  if (query.includes('soc') || query.includes('समाज')) {
    const s = EXPLORER_SUBJECTS.find((sub) => sub.id === 'sociology');
    if (s) return s;
  }
  if (query.includes('eco') || query.includes('अर्थ')) {
    const s = EXPLORER_SUBJECTS.find((sub) => sub.id === 'economics');
    if (s) return s;
  }
  if (query.includes('eng') || query.includes('अंग्रेजी')) {
    const s = EXPLORER_SUBJECTS.find((sub) => sub.id === 'english');
    if (s) return s;
  }
  if (query.includes('san') || query.includes('संस्कृत')) {
    const s = EXPLORER_SUBJECTS.find((sub) => sub.id === 'sanskrit');
    if (s) return s;
  }
  if (query.includes('hsc') || query.includes('गृह')) {
    const s = EXPLORER_SUBJECTS.find((sub) => sub.id === 'homescience');
    if (s) return s;
  }
  if (query.includes('drw') || query.includes('चित्रकला')) {
    const s = EXPLORER_SUBJECTS.find((sub) => sub.id === 'drawing');
    if (s) return s;
  }
  if (query.includes('ant') || query.includes('मानव')) {
    const s = EXPLORER_SUBJECTS.find((sub) => sub.id === 'anthropology');
    if (s) return s;
  }
  if (query.includes('geo') || query.includes('भूगोल')) {
    const s = EXPLORER_SUBJECTS.find((sub) => sub.id === 'geography');
    if (s) return s;
  }

  return EXPLORER_SUBJECTS[0];
}

// Helper to find a topic across all explorer subjects
export function findExplorerTopic(
  subjectId?: string,
  unitNumber?: number,
  topicId?: string
): { subject: ExplorerSubject; unit: ExplorerUnit; topic: ExplorerTopic } {
  const subject = getExplorerSubject(subjectId);
  const unit =
    subject.units.find((u) => u.unitNumber === unitNumber) || subject.units[0];
  
  // Try to find the exact topic in the unit, or across the whole subject
  let topic = topicId ? unit.topics.find((t) => t.id === topicId || t.notesTopicId === topicId) : undefined;
  if (!topic && topicId) {
    for (const u of subject.units) {
      const match = u.topics.find((t) => t.id === topicId || t.notesTopicId === topicId);
      if (match) {
        topic = match;
        break;
      }
    }
  }

  // Fallback to first topic of unit or a dynamically generated fallback with discipline-specific youtubeId
  if (!topic) {
    topic = unit.topics[0] || {
      id: `${subject.id}-${unit.unitNumber}-1`,
      sequence: `Topic ${unit.unitNumber}.1`,
      titleEn: unit.titleEn,
      titleHi: unit.titleHi,
      duration: '25:00',
      youtubeId: subject.id === 'history' ? 'WMopoZiIg1Q' :
                 subject.id === 'geography' ? 'r43m_H6Fz3Y' :
                 subject.id === 'sociology' ? '1b0V49aL-88' :
                 subject.id === 'hindi' ? 'V9n7Vd8i9wU' : 'zR7wQy6E4kE',
      educator: 'Academic Faculty Panel',
      channel: 'Verified Academic Stream',
      language: 'Hinglish',
    };
  }

  return { subject, unit, topic };
}

